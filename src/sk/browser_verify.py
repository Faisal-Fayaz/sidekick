"""An optional local browser verification pack (#520).

No required dependency: the pack detects a browser or Playwright install that
is already present and reports `unavailable` when none exists. The target URL
passes the same egress and SSRF gates as `read_url` before a browser is
launched. Everything else is a seam: a runner can be injected for tests, so the
suite never needs a real browser.

Residual risk, stated in the docs: a page can navigate itself to another URL
after the initial check. Those in-page navigations are not re-gated here.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

SCHEMA = 1
CHROME_BINARIES = (
    "google-chrome",
    "google-chrome-stable",
    "chromium",
    "chromium-browser",
)
Runner = Callable[[list[str]], tuple[int, str, str]]


@dataclass(frozen=True)
class Browser:
    kind: str  # "playwright" | "chrome"
    command: str


def detect() -> Browser | None:
    """An already-installed browser, or None. Never installs anything."""
    try:
        import importlib.util

        if importlib.util.find_spec("playwright") is not None:
            return Browser("playwright", sys.executable)
    except Exception:
        pass
    for name in CHROME_BINARIES:
        found = shutil.which(name)
        if found:
            return Browser("chrome", found)
    return None


def check_target(url: str) -> str:
    """The egress + SSRF decision for the URL, "" when it may be opened."""
    from .egress import check, hint, record
    from .tools.web import _url_blocked_twice

    target = str(url or "").strip()
    deny = check(target)
    record("browser:verify", target, deny)
    if deny:
        return f"egress blocked — {deny}. Allow it with `{hint(target)}` if you trust it."
    blocked = _url_blocked_twice(target)
    if blocked:
        return f"blocked by the SSRF guard: {blocked}"
    return ""


def build_command(
    url: str,
    *,
    snapshot: str = "",
    screenshot: str = "",
    emit_test: str = "",
    browser: Browser | None = None,
) -> list[str]:
    """The argv for one verification run. Empty when no browser is available."""
    tool = browser if browser is not None else detect()
    if tool is None:
        return []
    if tool.kind == "playwright":
        argv = [tool.command, "-m", "sk.browser_probe", url]
        if snapshot:
            argv += ["--snapshot", snapshot]
        if screenshot:
            argv += ["--screenshot", screenshot]
        if emit_test:
            argv += ["--emit-test", emit_test]
        return argv
    # Plain Chrome can render a page and dump its DOM. An accessibility tree
    # needs Playwright; the result says so rather than pretending.
    argv = [tool.command, "--headless=new", "--disable-gpu"]
    if screenshot:
        argv.append(f"--screenshot={screenshot}")
    argv += ["--dump-dom", url]
    return argv


def generate_test(url: str) -> str:
    """A small, editable Playwright test skeleton for the verified URL."""
    return (
        '"""Generated by `sk verify-browser --emit-test`. Edit before committing."""\n'
        "from playwright.sync_api import sync_playwright\n\n\n"
        "def test_page_loads():\n"
        "    with sync_playwright() as p:\n"
        "        browser = p.chromium.launch()\n"
        "        page = browser.new_page()\n"
        f"        page.goto({url!r})\n"
        "        assert page.title()\n"
        "        browser.close()\n"
    )


def verify(
    url: str,
    *,
    snapshot: str = "",
    screenshot: str = "",
    emit_test: str = "",
    runner: Runner | None = None,
    browser: Browser | None = None,
) -> dict:
    """Verify one URL. Returns a structured result; never raises on a page failure."""
    result: dict = {
        "schema": SCHEMA,
        "target": str(url or ""),
        "available": False,
        "ok": False,
        "browser": "",
        "snapshot": "",
        "screenshot": "",
        "test": "",
        "note": "",
    }
    tool = browser if browser is not None else detect()
    if tool is None:
        result["note"] = "No browser or Playwright install detected; nothing was launched."
        return result
    result["available"] = True
    result["browser"] = tool.kind

    refusal = check_target(url)
    if refusal:
        result["note"] = refusal
        return result

    argv = build_command(
        url, snapshot=snapshot, screenshot=screenshot, emit_test=emit_test, browser=tool
    )
    run = runner or (lambda args: _default_runner(args))
    try:
        code, out, err = run(argv)
    except Exception as e:  # noqa: BLE001 - a failed launch is a report
        result["note"] = f"browser launch failed: {type(e).__name__}: {str(e)[:200]}"
        return result
    result["ok"] = code == 0
    result["note"] = (
        (err or out)[:500]
        if code != 0
        else (
            "Chrome DOM dump — accessibility snapshot needs Playwright"
            if tool.kind == "chrome"
            else ""
        )
    )
    if snapshot and out:
        try:
            Path(snapshot).expanduser().write_text(out, encoding="utf-8")
            result["snapshot"] = str(snapshot)
        except Exception:
            result["note"] += " (snapshot could not be written)"
    for key, path in (("screenshot", screenshot), ("test", emit_test)):
        if path:
            try:
                if key == "test":
                    Path(path).expanduser().write_text(generate_test(url), encoding="utf-8")
                result[key] = str(path)
            except Exception:
                result["note"] += f" ({key} could not be written)"
    return result


def _default_runner(argv: list[str]) -> tuple[int, str, str]:
    try:
        completed = subprocess.run(argv, capture_output=True, text=True, timeout=120, check=False)
        return completed.returncode, completed.stdout or "", completed.stderr or ""
    except Exception as e:  # noqa: BLE001 - a launch failure is a report
        return 127, "", f"{type(e).__name__}: {e}"
